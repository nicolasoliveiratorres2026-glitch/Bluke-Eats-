import turtle
t = turtle.Turtle()
s = turtle.Screen()
t.shape("turtle")
t.speed(0)
t.fillcolor("#01a2ff")
t.penup()
t.setx(-100)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(100)
    t.right(90)
t.end_fill()
t.fillcolor("white")
t.penup()
t.goto(t.xcor() + 10, t.ycor() - 20)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(30)
    t.right(90)
t.end_fill()
t.penup()
t.setx(t.xcor() + 50)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(30)
    t.right(90)
t.end_fill()
t.penup()
t.goto(t.xcor() + 5, t.ycor() - 10)
t.pendown()
t.color("black")
t.begin_fill()
for i in range(4):
    t.fd(20)
    t.right(90)
t.end_fill()
t.penup()
t.setx(t.xcor() - 50)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(20)
    t.right(90)
t.end_fill()
t.penup()
t.sety(t.ycor() - 40)
t.pendown()
t.right(90)
t.fd(20)
t.left(90)
t.fd(70)
t.left(90)
t.fd(20)
t.bk(20)
t.right(90)
t.bk(28)
t.right(90)
t.fillcolor("#fc77f6")
t.begin_fill()
t.fd(40)
t.right(135)
t.fd(10)
t.left(90)
t.fd(10)
t.right(135)
t.fd(40)
t.right(90)
t.fd(20)
t.end_fill()
t.hideturtle()
turtle.done()
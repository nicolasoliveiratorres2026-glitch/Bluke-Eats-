import turtle
from PIL import Image
img = Image.open("corpo.png")
img = img.resize((40, 40))
img.save("corpo.png")
t = turtle.Turtle()
s = turtle.Screen()
t.shape("turtle")
t.speed(0)
t.fillcolor("#01a2ff")
t.penup()
t.setx(-100)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(100)
    t.right(90)
t.end_fill()
t.fillcolor("white")
t.penup()
t.goto(t.xcor() + 10, t.ycor() - 20)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(30)
    t.right(90)
t.end_fill()
t.penup()
t.setx(t.xcor() + 50)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(30)
    t.right(90)
t.end_fill()
t.penup()
t.goto(t.xcor() + 5, t.ycor() - 10)
t.pendown()
t.color("black")
t.begin_fill()
for i in range(4):
    t.fd(20)
    t.right(90)
t.end_fill()
t.penup()
t.setx(t.xcor() - 50)
t.pendown()
t.begin_fill()
for i in range(4):
    t.fd(20)
    t.right(90)
t.end_fill()
t.penup()
t.sety(t.ycor() - 40)
t.pendown()
t.begin_fill()
t.right(90)
t.fd(20)
t.left(90)
t.fd(70)
t.left(90)
t.fd(30)
t.left(90)
t.fd(70)
t.left(90)
t.fd(30)
t.end_fill()
t.bk(30)
t.left(90)
t.color("white")
t.right(45)
t.begin_fill()
t.fd(15)
t.left(90)
t.fd(15)
t.end_fill()
t.penup()
t.right(45)
t.bk(15)
t.fd(62.5)
t.left(45)
t.pendown()
t.begin_fill()
t.bk(15)
t.right(90)
t.bk(15)
t.end_fill()
t.hideturtle()
turtle.done()